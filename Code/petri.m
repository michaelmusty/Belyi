// ================================================================================
// Petri classification: the canonical ideal of a non-hyperelliptic curve, g >= 5
// ================================================================================
//
// For a non-hyperelliptic curve of genus g the canonical model lives in
// P^(g-1) with homogeneous coordinates the echelonized basis f_1, ..., f_g
// of S_2(Gamma); we work in the affine coordinates on the patch f_g <> 0,
//
//     x_i = f_i / f_g,   i = 1, ..., g-1,
//
// exactly as genus3nonhyperelliptic.m works on f_3 <> 0 and genus4.m on
// f_4 <> 0.  The hyperplane class is the canonical class, of degree 2g-2.
//
// COUNTING is intrinsic to the genus and does not see the Petri case:
//
//     #monomials of degree d        = Binomial(d + g - 1, g - 1)
//     h^0(dK)                       = (2d - 1)(g - 1)        (d >= 2)
//     dim I_d                       = Binomial(d+g-1, g-1) - (2d-1)(g-1)
//     dim I_2 = (g-2)(g-3)/2,  dim I_3 = Binomial(g+2, 3) - 5(g-1)
//
// while a HYPERELLIPTIC curve has canonical image the rational normal curve
// of degree g-1, with a degree-2 kernel of dimension (g-1)(g-2)/2 instead.
// Hyperelliptic curves never reach this file: belyi_main.m runs
// TriangleHyperellipticTest first and routes them away, and this file does
// NOT retest -- it reports the hyperelliptic dimension as a routing error.
//
// PETRI'S THEOREM (g >= 4).  The canonical ideal is generated by quadrics,
// UNLESS the curve is trigonal or (g = 6 only) a smooth plane quintic; in
// those exceptional cases the quadrics cut out a surface -- the rational
// normal scroll swept by the g^1_3, or the Veronese surface in P^5 -- and
// the ideal needs g-3 cubic generators on top of S_1 * I_2.  Only the SPAN
// of the products moves, never dim I_d, so the whole classification is two
// kernel dimensions and one rank:
//
//     case                 dim(degree-2 kernel)   rank(S_1 * I_2) in I_3
//     hyperelliptic        (g-1)(g-2)/2           (routed before this runs)
//     general              (g-2)(g-3)/2           dim I_3
//     trigonal / quintic   (g-2)(g-3)/2           dim I_3 - (g-3)
//
// "General" means Petri-general -- the quadrics generate -- not generic in
// moduli: a bielliptic or tetragonal genus-5 curve is "General" for us,
// which is the right notion because it is exactly the question "which
// equations do we have to compute".
//
// GENUS 6.  The trigonal curve and the plane quintic have the same
// dim I_2 = 6, the same deficiency 3, and their surfaces (quartic scroll,
// Veronese) have identical Hilbert functions in every degree, so no kernel
// dimension at any degree separates them.  None is needed: the equations
// recipe is the same for both, so at g = 6 the verdict is "Exceptional".
//
// Everything is EXACT LINEAR ALGEBRA IN MONOMIAL COORDINATES, never an
// orthogonal projection (the genus-4 lesson: a projection is a
// transcendental combination of the K-rational vectors and unrecognizable
// at any precision).  The kernels are RREF'd, and in the exceptional case
// the cubics are isolated by reducing the degree-3 kernel modulo an RREF
// basis of S_1 * I_2 and RREF-ing the survivors -- the genus-4
// cubic-modulo-quadric trick one level up.
//
// ROWS ARE HOMOGENEOUS.  A degree-d monomial is the series
// f_1^(m_1) ... f_(g-1)^(m_(g-1)) f_g^(d - |m|), a product of the normalized
// forms, never the affine x^m = f^m / f_g^d that genus3nonhyperelliptic.m
// and genus4.m use.  The relations are identical -- every affine row is the
// homogeneous one divided by the single series f_g^d -- so the coefficient
// vectors, their indexing by CanonicalMonomials, the RREF and the affine
// torus weights returned are all the same; but products of forms converge
// on the whole disc, while f_i/f_g has a pole at every other zero of f_g
// (11T6 member 2: coefficients of 10^19 within 200 terms, R ~ 0.74, and a
// degree-3 kernel that NumericalKernel could not recover at radius 1).  The
// affine chart is the rescaler's business, for its weight-zero coefficient,
// and it gets affine-indexed lists; it is not a reason to divide series.
// Doc/adr-series-stage-echelonization.md §4.
//
// Specified in Doc/SPEC-genus5plus.md §3; this file is also the Stage-0
// computation of §8.

import "serieskernel.m" : SeriesZeroify, SeriesRREF, SeriesColumnsAvailable,
    SeriesKernel, SeriesReduceModRREF, SeriesNormalizedForms;

// --------------------------------------------------------------------------
// the monomial basis and the counting
// --------------------------------------------------------------------------

intrinsic CanonicalMonomials(g::RngIntElt, d::RngIntElt) -> SeqEnum
  {Exponent vectors [a_1, ..., a_(g-1)] with a_1 + ... + a_(g-1) le d: the
   affine monomials of degree at most d in the g-1 coordinates x_i = f_i/f_g
   of the canonical patch f_g <> 0, which are the degree-d monomials in g
   variables dehomogenized by f_g^d.  Listed in increasing total degree,
   lexicographically decreasing within a degree, with the weight-zero
   monomial [0, ..., 0] LAST -- the ordering Genus4Monomials uses for g = 4,
   which TriangleRescaleCoefficients' default pivot assumes.  There are
   Binomial(d + g - 1, g - 1) of them.}

  require g ge 2 : "g must be at least 2";
  require d ge 0 : "d must be nonnegative";
  n := g - 1;
  // all [a_1..a_k] with sum e, a_1 descending, recursively
  comps := function(e, k)
    if k eq 1 then
      return [[e]];
    end if;
    out := [];
    for a := e to 0 by -1 do
      for t in $$(e - a, k - 1) do
        Append(~out, [a] cat t);
      end for;
    end for;
    return out;
  end function;
  mons := [];
  for e in [1..d] do
    mons cat:= comps(e, n);
  end for;
  Append(~mons, [0 : i in [1..n]]);
  assert #mons eq Binomial(d + g - 1, g - 1);
  return mons;
end intrinsic;

intrinsic CanonicalIdealDimension(g::RngIntElt, d::RngIntElt) -> RngIntElt
  {dim I_d for the canonical ideal of a NON-hyperelliptic curve of genus g:
   Binomial(d + g - 1, g - 1) - (2d - 1)(g - 1) for d >= 2, since h^0(dK) is
   (2d - 1)(g - 1) there; 0 for d <= 1.  The same in every Petri case --
   only the span of products of lower-degree generators depends on the
   case.  For g = 4 this agrees with Genus4IdealDimension.}

  require g ge 3 : "g must be at least 3";
  require d ge 0 : "d must be nonnegative";
  if d le 1 then
    return 0;
  end if;
  return Binomial(d + g - 1, g - 1) - (2*d - 1)*(g - 1);
end intrinsic;

// --------------------------------------------------------------------------
// the classification
// --------------------------------------------------------------------------

intrinsic TrianglePetriTest(Sk::SeqEnum, Gamma::GrpPSL2Tri) -> MonStgElt, SeqEnum, SeqEnum, SeqEnum, SeqEnum
  {Genus g >= 5, NOT hyperelliptic: classify the canonical curve from the
   power series alone and return its quadrics, and in the exceptional case
   its cubics.

   Input: Sk, an echelonized basis for the space of weight-2 forms, as
          returned by PowerSeriesBasis; Gamma, a triangle subgroup of genus
          g >= 5 that TriangleHyperellipticTest has ALREADY found to be
          non-hyperelliptic.
   Output: petri_case, one of "General", "Trigonal" (g <> 6) or
           "Exceptional" (g = 6: trigonal or plane quintic, deliberately
           undistinguished);
           quadrics, the RREF basis of I_2, (g-2)(g-3)/2 coefficient lists
           indexed by CanonicalMonomials(g, 2);
           cubics, in the exceptional case the g-3 cubic generators modulo
           S_1 * I_2, RREF'd, indexed by CanonicalMonomials(g, 3); empty
           otherwise;
           vals2 and vals3, the affine weights of the degree-2 and degree-3
           monomials (valuations of x^m = f^m/f_g^d), in the same orders.
   Also assigns Gamma`TrianglePetriCase, Gamma`TriangleCanonicalQuadrics and
   Gamma`TriangleCanonicalCubics.

   A wrong kernel dimension is an ERROR, never a verdict: at this point the
   curve is known to be non-hyperelliptic of genus g, so dim I_2 and dim I_3
   are forced, and anything else is a precision failure -- or, for the
   hyperelliptic dimension (g-1)(g-2)/2, a routing bug, which the message
   says.  Every such error prints the numbers it was decided on.}

  gg := Genus(Gamma);   // NOT `g`: a ring generator named g would rebind it
  require gg ge 5 :
      "TrianglePetriTest is for genus >= 5 (genus 4 is genus4.m, genus 3 is genus3nonhyperelliptic.m)";
  require #Sk eq gg :
      Sprintf("Sk should be an echelonized basis of S_2(Gamma), which has dimension %o in genus %o; got %o forms", gg, gg, #Sk);

  prec := Precision(BaseRing(Parent(Sk[1][1])));
  eps := 10^(-prec/2);   // rational exponent -> FldReElt; (prec div 2) gives
                         // FldRatElt, which NumericalKernel rejects
  CC := BaseRing(Parent(Sk[1][1]));
  if not assigned Gamma`TriangleNumericalPrecision then
    Gamma`TriangleNumericalPrecision := prec;
  end if;
  Delta := ContainingTriangleGroup(Gamma);
  _, kappa := TrianglePhi(Delta);

  vprintf Shimura : "Determining the Petri classification (genus %o, prec %o)...\n", gg, prec;

  // ------------------------------------------------------------------
  // the affine coordinates and the stride
  // ------------------------------------------------------------------
  // HOMOGENEOUS rows (2026-11-12).  A degree-d monomial is built as
  // f_1^(m_1) ... f_(g-1)^(m_(g-1)) * f_g^(d - |m|), a product of holomorphic
  // forms, rather than as the affine x^m = f^m / f_g^d: the two have the
  // same relations (every affine row is the homogeneous row divided by the
  // one series f_g^d), but the affine series have poles at every other zero
  // of f_g inside the disc and their coefficients then grow like R^-n (11T6
  // member 2: 10^19 within 200 terms), which wrecks the kernel.  The
  // coefficient vectors, their indexing by CanonicalMonomials, and the
  // torus weights returned (affine convention: a shift by -d*s_g per degree)
  // are unchanged.
  vprintf Shimura : "\tCreating the %o normalized forms f_i(kappa w)...\n", gg;
  fs := SeriesNormalizedForms(Sk, kappa, eps);
  svals := [Valuation(f) : f in fs];
  // s_1 < ... < s_g for an echelonized basis; anything else is the series
  // stage's echelonization gone degenerate (see hyperelliptic.m, same check)
  require #Set(svals) eq gg and svals eq Sort(svals) :
      Sprintf("the echelonized basis is numerically degenerate at prec %o: the forms vanish to orders %o at the expansion point, which should be strictly increasing; raise prec", prec, svals);
  sigma := DefiningPermutation(Gamma);
  aa := DefiningABC(Gamma)[1];
  s0 := #CycleDecomposition(sigma[1])[1];
  e := aa div s0;
  require e*s0 eq aa :
      Sprintf("the ramification index %o at the expansion point does not divide a = %o", s0, aa);
  // forms have exponents in one residue class mod e, so their differences
  // are divisible by e; a degree-d product's exponents are all = d*s_1 mod e
  require &and[(s - svals[1]) mod e eq 0 : s in svals] :
      Sprintf("the orders of vanishing %o are not congruent mod the stabilizer order %o", svals, e);
  vprintf Shimura : "\torders of vanishing of the forms at P: %o, stride %o\n", svals, e;

  nhyp := ((gg - 1)*(gg - 2)) div 2;
  nI2 := CanonicalIdealDimension(gg, 2);
  nI3 := CanonicalIdealDimension(gg, 3);

  // the homogeneous monomial series f^m * f_g^(d - |m|) of a list of affine
  // exponent vectors (length g-1, |m| <= d)
  // exponent vectors as compact strings, so a list of pivots prints on one line
  MonNames := function(mons);
    return "[" cat (#mons eq 0 select "" else &cat[(i eq 1 select "" else " ") cat &cat[IntegerToString(a) : a in mons[i]] : i in [1..#mons]]) cat "]";
  end function;
  MonSeries := function(mons, d);
    return [&*[fs[i]^(m[i]) : i in [1..gg-1]]*fs[gg]^(d - &+m) : m in mons];
  end function;
  // the numerical kernel of the degree-d monomial series, with the column
  // window measured, strided and reported (SPEC §2a, §3a)
  DegreeKernel := function(d, mons);
    ser := MonSeries(mons, d);
    vals := [Valuation(h) : h in ser];
    assert vals eq [&+[m[i]*svals[i] : i in [1..gg-1]] + (d - &+m)*svals[gg] : m in mons];
    minval := Min(vals);
    navail := SeriesColumnsAvailable(ser, minval, e);
    wanted := Max(4*#ser, #ser + 20);
    ncols := Min(navail, wanted);
    error if ncols lt #ser + 5,
        Sprintf("not enough terms in the power series basis for the degree-%o monomials: %o strided columns available, %o needed, %o wanted; raise prec",
                d, navail, #ser + 5, wanted);
    vprintf Shimura : "\tForming matrix of monomials of degree %o (%o monomials, %o columns of %o available, %o wanted, stride %o)...\n",
        d, #ser, ncols, navail, wanted, e;
    ker := SeriesKernel(ser, minval, e, ncols, eps, CC);
    // weights in the AFFINE convention the rescaler assumes: subtract d*s_g
    return ker, [v - d*svals[gg] : v in vals];
  end function;

  // ------------------------------------------------------------------
  // degree 2: I_2 itself
  // ------------------------------------------------------------------
  mons2 := CanonicalMonomials(gg, 2);
  k2, vals2 := DegreeKernel(2, mons2);
  vprintf Shimura : "\tdegree-2 kernel has dimension %o (expected %o for non-hyperelliptic, %o for hyperelliptic)\n", #k2, nI2, nhyp;
  error if #k2 eq nhyp,
      Sprintf("the degree-2 kernel has the HYPERELLIPTIC dimension %o = (g-1)(g-2)/2, not %o = (g-2)(g-3)/2: TriangleHyperellipticTest should have routed this curve away before TrianglePetriTest was called -- a routing bug, or the precision is too low for the hyperelliptic test", nhyp, nI2);
  error if #k2 ne nI2,
      Sprintf("the degree-2 kernel has dimension %o, expected %o = (g-2)(g-3)/2 for a non-hyperelliptic curve of genus %o; raise prec", #k2, nI2, gg);
  ksc := Max([Max([Abs(c) : c in v]) : v in k2]);
  Q, qpiv := SeriesRREF(k2, ksc*10^(-(prec div 2)));
  error if #Q ne nI2,
      Sprintf("the RREF of I_2 has %o rows, expected %o; raise prec", #Q, nI2);
  Q := [SeriesZeroify(q, prec) : q in Q];
  vprintf Shimura : "\tRREF of I_2: %o quadrics, pivots at monomials %o\n", #Q, MonNames([mons2[p] : p in qpiv]);

  // ------------------------------------------------------------------
  // degree 3: I_3, and the rank of S_1 * I_2 inside it
  // ------------------------------------------------------------------
  mons3 := CanonicalMonomials(gg, 3);
  k3, vals3 := DegreeKernel(3, mons3);
  vprintf Shimura : "\tdegree-3 kernel has dimension %o (expected dim I_3 = %o)\n", #k3, nI3;
  error if #k3 ne nI3,
      Sprintf("the degree-3 kernel has dimension %o, expected dim I_3 = %o for genus %o; raise prec", #k3, nI3, gg);

  // S_1 * I_2 in degree-3 monomial coordinates: each quadric times each of
  // x_1, ..., x_(g-1), 1 -- g * dim I_2 products
  R := PolynomialRing(CC, gg - 1);
  Mon := func<m | &*[R.i^(m[i]) : i in [1..gg-1]]>;
  Qpols := [&+[q[i]*Mon(mons2[i]) : i in [1..#mons2]] : q in Q];
  mults := [R.i : i in [1..gg-1]] cat [R!1];
  prods := [];
  for Qp in Qpols do
    for f in mults do
      Append(~prods, [MonomialCoefficient(f*Qp, Mon(m)) : m in mons3]);
    end for;
  end for;
  psc := Max([Max([Abs(c) : c in r]) : r in prods]);
  Pr, ppiv := SeriesRREF(prods, psc*10^(-(prec div 2)));
  rank := #Pr;
  vprintf Shimura : "\tS_1 * I_2 (%o products) has rank %o of dim I_3 = %o (deficiency %o; general 0, exceptional %o)\n",
      #prods, rank, nI3, nI3 - rank, gg - 3;

  cubics := [];
  if rank eq nI3 then
    petri_case := "General";
  elif rank eq nI3 - (gg - 3) then
    petri_case := gg eq 6 select "Exceptional" else "Trigonal";
    // isolate the g-3 missing cubics: reduce the degree-3 kernel modulo the
    // RREF basis of S_1 * I_2, drop what vanishes, RREF the survivors
    vprintf Shimura : "\tisolating %o cubics modulo S_1 * I_2...\n", gg - 3;
    k3sc := Max([Max([Abs(c) : c in v]) : v in k3]);
    red := [];
    for v in k3 do
      u := SeriesReduceModRREF(v, Pr, ppiv);
      if Max([Abs(c) : c in u]) gt k3sc*10^(-(prec div 3)) then
        Append(~red, u);
      end if;
    end for;
    error if #red eq 0,
        "every degree-3 kernel vector reduced to zero modulo S_1 * I_2, yet the rank said otherwise; raise prec";
    rsc := Max([Max([Abs(c) : c in u]) : u in red]);
    Cb, cpiv := SeriesRREF(red, rsc*10^(-(prec div 2)));
    error if #Cb ne gg - 3,
        Sprintf("the cubics modulo S_1 * I_2 span %o dimensions, expected %o = g - 3; raise prec", #Cb, gg - 3);
    cubics := [SeriesZeroify(c, prec) : c in Cb];
    vprintf Shimura : "\tRREF of the cubics: %o rows, pivots at monomials %o\n", #cubics, MonNames([mons3[p] : p in cpiv]);
  else
    error Sprintf("S_1 * I_2 has rank %o in I_3 of dimension %o: neither the general value %o nor the exceptional value %o; raise prec",
                  rank, nI3, nI3, nI3 - (gg - 3));
  end if;

  Gamma`TrianglePetriCase := petri_case;
  Gamma`TriangleCanonicalQuadrics := Q;
  Gamma`TriangleCanonicalCubics := cubics;
  vprintf Shimura : "Petri case: %o (%o quadrics, %o cubics)\n", petri_case, #Q, #cubics;
  return petri_case, Q, cubics, vals2, vals3;
end intrinsic;
